import { readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import db from "../db.js";
import errs from "../lib/error.js";
import { cidrContains, normalizeCidr } from "../lib/ip-cidr.js";
import { nginx as logger } from "../logger.js";
import proxyHostModel from "../models/proxy_host.js";
import internalAuditLog from "./audit-log.js";
import internalNginx from "./nginx.js";
import internalProxyHost from "./proxy-host.js";

const TABLE = "npmplus_crowdsec_exception";
const HOST_TABLE = "npmplus_crowdsec_exception_host";
// only meant for testing, the same variable as in crowdsec.js
const nginxConfDir = process.env.NPMPLUS_NGINX_CONF_DIR || "/usr/local/nginx/conf/conf.d";
// conf.d/*.conf is included at http level, so geo and map blocks are allowed there
const includeFile = path.join(nginxConfDir, "crowdsec-exceptions.conf");
// set by every proxy host (templates/proxy_host.conf)
const HOST_MARKER = "set $crowdsec_host_id ";
// larger ranges would exempt whole providers from the bouncer and AppSec; rows stored with an older, looser limit
// are kept in the database but no longer written to nginx (the ui marks them)
const MIN_PREFIX = { minPrefix4: 16, minPrefix6: 32 };
const MAX_EXCEPTIONS = 500;
const CONTROL_CHARS = /\p{Cc}/u;

const parseJson = (value, fallback) => {
	if (typeof value !== "string") return value ?? fallback;
	try {
		return JSON.parse(value);
	} catch {
		return fallback;
	}
};

// all writes (and the regeneration at startup) run one after another
let queue = Promise.resolve();
const serialize = (fn) => {
	const run = queue.then(fn, fn);
	queue = run.catch(() => {});
	return run;
};

/**
 * @returns {Promise<{exceptions: Object[], hosts: Map<Number, Object>}>}
 *          links to deleted proxy hosts are removed
 */
const load = async () => {
	const hostRows = await db()("proxy_host").select("id", "domain_names", "enabled");
	const hosts = new Map(
		hostRows.map((h) => [
			h.id,
			{ id: h.id, domain_names: parseJson(h.domain_names, []), enabled: Boolean(h.enabled) },
		]),
	);
	const links = await db()(HOST_TABLE).select("exception_id", "proxy_host_id");
	if (links.some((l) => !hosts.has(l.proxy_host_id))) {
		await db()(HOST_TABLE).whereNotIn("proxy_host_id", db()("proxy_host").select("id")).delete();
	}
	const hostIds = new Map();
	for (const l of links) {
		if (!hosts.has(l.proxy_host_id)) continue;
		if (!hostIds.has(l.exception_id)) hostIds.set(l.exception_id, []);
		hostIds.get(l.exception_id).push(l.proxy_host_id);
	}
	const rows = await db()(TABLE).select("id", "value", "description", "scope").orderBy("id");
	const exceptions = rows.map((r) => ({
		id: r.id,
		value: r.value,
		description: r.description ?? "",
		scope: r.scope === "hosts" ? "hosts" : "global",
		proxy_host_ids: r.scope === "hosts" ? (hostIds.get(r.id) ?? []).sort((a, b) => a - b) : [],
	}));
	return { exceptions, hosts };
};

const format = (exception, hosts) => ({
	...exception,
	effective: Boolean(normalizeCidr(exception.value, MIN_PREFIX)),
	proxy_hosts: exception.proxy_host_ids.map((id) => hosts.get(id)).filter(Boolean),
});

/**
 * The include for nginx, only normalised addresses and numeric host ids end up in it
 *
 * @param   {Object[]} exceptions
 * @returns {String}
 */
const render = (exceptions) => {
	const global = new Set();
	const perHost = new Map();
	for (const e of exceptions) {
		// stored values are validated on write, this protects the config from rows edited by hand
		const value = normalizeCidr(e.value, MIN_PREFIX);
		if (!value) {
			logger.warn(`CrowdSec exceptions: ${String(e.value).slice(0, 64)} is ignored, the range is too large`);
			continue;
		}
		if (e.scope === "global") {
			global.add(value);
			continue;
		}
		for (const id of e.proxy_host_ids) {
			if (!Number.isSafeInteger(id) || id < 1) continue;
			if (!perHost.has(id)) perHost.set(id, new Set());
			perHost.get(id).add(value);
		}
	}

	const geo = (name, values) =>
		[`geo $${name} {`, "  default 0;", ...[...values].map((v) => `  ${v} 1;`), "}", ""].join("\n");
	const hostIds = [...perHost.keys()].sort((a, b) => a - b);

	return [
		"# Generated by NPMplus from the CrowdSec exceptions (CrowdSec page), changes are overwritten.",
		"# Matching client addresses ($remote_addr, after real ip handling) skip the bouncer and AppSec,",
		"# see the access_by_lua_block in crowdsec.conf.",
		"",
		geo("crowdsec_exempt_global", global),
		"# every proxy host sets its id, other hosts keep the default",
		"map $host $crowdsec_host_id {",
		'  default "";',
		"}",
		"",
		...hostIds.map((id) => geo(`crowdsec_exempt_host_${id}`, perHost.get(id))),
		"map $crowdsec_host_id $crowdsec_exempt_host {",
		"  default 0;",
		...hostIds.map((id) => `  ${id} $crowdsec_exempt_host_${id};`),
		"}",
		"",
	].join("\n");
};

const readCurrent = async () => {
	try {
		return await readFile(includeFile, "utf8");
	} catch (err) {
		if (err.code === "ENOENT") return null;
		throw err;
	}
};

/**
 * Writes the include and checks it with nginx -t, the previous file is restored if nginx rejects it
 *
 * @param   {Object[]} exceptions
 * @returns {Promise<Boolean>}  whether the file changed
 */
const writeInclude = async (exceptions) => {
	const text = render(exceptions);
	const old = await readCurrent();
	if (old === text) return false;
	await writeFile(includeFile, text, { encoding: "utf8" });
	try {
		await internalNginx.test();
	} catch (err) {
		if (old === null) await rm(includeFile, { force: true });
		else await writeFile(includeFile, old, { encoding: "utf8" });
		throw new errs.ValidationError(`Could not apply the CrowdSec exceptions: ${err.message}`);
	}
	return true;
};

/**
 * Proxy host configs written before the exceptions existed don't set $crowdsec_host_id yet
 *
 * @param {Access}   access
 * @param {Number[]} hostIds
 */
const ensureHostConfigs = async (access, hostIds) => {
	for (const id of hostIds) {
		try {
			const text = await readFile(internalNginx.getConfigName("proxy_host", id), "utf8").catch(() => "");
			if (text.includes(HOST_MARKER)) continue;
			const host = await internalProxyHost.get(access, {
				id,
				expand: ["certificate", "access_lists.[clients,items]", "locations.access_lists.[clients,items]"],
			});
			if (!host.enabled) continue;
			await internalNginx.configure(proxyHostModel, "proxy_host", host, { skipReload: true });
		} catch (err) {
			logger.error(`CrowdSec exceptions: could not regenerate the config of proxy host ${id}: ${err.message}`);
		}
	}
};

/**
 * @param   {Object}              data
 * @param   {Map<Number, Object>} hosts
 * @returns {{value: String, description: String, scope: String, proxy_host_ids: Number[]}}
 */
const validate = (data, hosts) => {
	const value = normalizeCidr(String(data.value ?? "").trim(), MIN_PREFIX);
	if (!value) {
		throw new errs.ValidationError(
			"Not a valid IP address or CIDR range (IPv4 ranges need a prefix of at least /16, IPv6 ranges of at least /32)",
		);
	}
	const description = String(data.description ?? "").trim();
	if (description.length > 255 || CONTROL_CHARS.test(description)) {
		throw new errs.ValidationError("The description must be a single line of at most 255 characters");
	}
	const scope = data.scope === "hosts" ? "hosts" : "global";
	let ids = [];
	if (scope === "hosts") {
		ids = [...new Set(data.proxy_host_ids ?? [])].sort((a, b) => a - b);
		if (ids.length === 0) throw new errs.ValidationError("Select at least one proxy host");
		const unknown = ids.filter((id) => !hosts.has(id));
		if (unknown.length > 0) throw new errs.ValidationError(`Unknown proxy host: ${unknown.join(", ")}`);
	}
	return { value, description, scope, proxy_host_ids: ids };
};

/**
 * Applies the new list to nginx first and stores it only if nginx accepted it
 *
 * @param {Access}   access
 * @param {Object[]} next      the complete new list
 * @param {Function} persist   writes the change to the database
 * @param {Number[]} newHosts  proxy hosts which have to set $crowdsec_host_id
 */
const apply = async (access, next, persist, newHosts) => {
	const changed = await writeInclude(next);
	try {
		await persist();
	} catch (err) {
		// keep nginx in line with the database
		await writeInclude((await load()).exceptions).catch(() => {});
		throw err;
	}
	if (newHosts.length > 0) await ensureHostConfigs(access, newHosts);
	if (changed || newHosts.length > 0) await internalNginx.reload();
};

const replaceHosts = async (trx, id, hostIds) => {
	await trx(HOST_TABLE).where({ exception_id: id }).delete();
	if (hostIds.length > 0) {
		await trx(HOST_TABLE).insert(hostIds.map((proxy_host_id) => ({ exception_id: id, proxy_host_id })));
	}
};

const internalCrowdsecExceptions = {
	/**
	 * @param   {Access}  access
	 * @returns {Promise<Object[]>}
	 */
	getAll: async (access) => {
		access.canAdmin();
		const { exceptions, hosts } = await load();
		return exceptions.map((e) => format(e, hosts));
	},

	/**
	 * @param   {Access}  access
	 * @param   {Object}  data
	 * @returns {Promise<Object>}
	 */
	create: async (access, data) =>
		serialize(async () => {
			access.canAdmin();
			const { exceptions, hosts } = await load();
			if (exceptions.length >= MAX_EXCEPTIONS) {
				throw new errs.ValidationError(`At most ${MAX_EXCEPTIONS} exceptions are possible`);
			}
			const row = validate(data, hosts);
			let id;
			await apply(
				access,
				[...exceptions, row],
				() =>
					db().transaction(async (trx) => {
						const { proxy_host_ids, ...fields } = row;
						const inserted = await trx(TABLE).insert(fields, ["id"]);
						id = typeof inserted[0] === "object" ? inserted[0].id : inserted[0];
						await replaceHosts(trx, id, proxy_host_ids);
					}),
				row.proxy_host_ids,
			);
			const result = { id, ...row };
			await internalAuditLog.add(access, {
				action: "created",
				object_type: "crowdsec",
				meta: { ...result, id: "exception", exception_id: id },
			});
			return format(result, hosts);
		}),

	/**
	 * @param   {Access}  access
	 * @param   {Number}  id
	 * @param   {Object}  data
	 * @returns {Promise<Object>}
	 */
	update: async (access, id, data) =>
		serialize(async () => {
			access.canAdmin();
			const { exceptions, hosts } = await load();
			const old = exceptions.find((e) => e.id === id);
			if (!old) throw new errs.ItemNotFoundError(id);
			const row = validate({ ...old, ...data }, hosts);
			await apply(
				access,
				exceptions.map((e) => (e.id === id ? { id, ...row } : e)),
				() =>
					db().transaction(async (trx) => {
						const { proxy_host_ids, ...fields } = row;
						await trx(TABLE).where({ id }).update(fields);
						await replaceHosts(trx, id, proxy_host_ids);
					}),
				row.proxy_host_ids.filter((h) => !old.proxy_host_ids.includes(h)),
			);
			const result = { id, ...row };
			await internalAuditLog.add(access, {
				action: "updated",
				object_type: "crowdsec",
				meta: { ...result, id: "exception", exception_id: id },
			});
			return format(result, hosts);
		}),

	/**
	 * @param   {Access}  access
	 * @param   {Number}  id
	 * @returns {Promise<Boolean>}
	 */
	delete: async (access, id) =>
		serialize(async () => {
			access.canAdmin();
			const { exceptions } = await load();
			const old = exceptions.find((e) => e.id === id);
			if (!old) throw new errs.ItemNotFoundError(id);
			await apply(
				access,
				exceptions.filter((e) => e.id !== id),
				() =>
					db().transaction(async (trx) => {
						await trx(HOST_TABLE).where({ exception_id: id }).delete();
						await trx(TABLE).where({ id }).delete();
					}),
				[],
			);
			await internalAuditLog.add(access, {
				action: "deleted",
				object_type: "crowdsec",
				meta: { ...old, id: "exception", exception_id: id },
			});
			return true;
		}),

	/**
	 * The address NPMplus sees for this request and the exceptions which already cover it
	 *
	 * @param   {Access}  access
	 * @param   {String}  ip  the client ip of the request (after real ip handling in nginx)
	 * @returns {Promise<{ip: String, exempt_global: Boolean, exempt_proxy_host_ids: Number[]}>}
	 */
	getClientIp: async (access, ip) => {
		access.canAdmin();
		const value = normalizeCidr(String(ip ?? "")) ?? "";
		const result = { ip: value, exempt_global: false, exempt_proxy_host_ids: [] };
		if (!value || value.includes("/")) return { ...result, ip: "" };
		const { exceptions } = await load();
		const hostIds = new Set();
		for (const e of exceptions) {
			if (!cidrContains(e.value, value)) continue;
			if (e.scope === "global") result.exempt_global = true;
			for (const h of e.proxy_host_ids) hostIds.add(h);
		}
		result.exempt_proxy_host_ids = [...hostIds].sort((a, b) => a - b);
		return result;
	},

	/**
	 * Writes the include at startup (the image only contains crowdsec.conf.disabled), nginx is reloaded afterwards
	 * by the caller, errors are only logged so a broken include never stops the start
	 *
	 * @returns {Promise}
	 */
	startup: () =>
		serialize(async () => {
			try {
				await writeInclude((await load()).exceptions);
			} catch (err) {
				logger.error(`CrowdSec exceptions: ${err.message}`);
			}
		}),

	render,
};

export default internalCrowdsecExceptions;
